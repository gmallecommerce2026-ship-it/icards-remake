// Sinh font tự host từ gói @fontsource (npm), thay cho next/font/google.
// Chạy: npm run fonts:build  -> tạo public/fonts/*.woff2 và src/styles/local-fonts.css
import { readFileSync, writeFileSync, copyFileSync, mkdirSync, rmSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
// weights/styles lấy từ cấu hình next/font/google cũ trong code
const FONTS = [
  { pkg: "be-vietnam-pro", weights: [400, 500, 600, 700], styles: ["normal", "italic"] },
  { pkg: "cormorant-garamond", weights: [400, 500, 600, 700], styles: ["normal", "italic"] },
  { pkg: "great-vibes", weights: [400], styles: ["normal"] },
  { pkg: "space-mono", weights: [400, 700], styles: ["normal"] },
  { pkg: "oswald", weights: [500, 700], styles: ["normal"] },
];
// Subset giống cấu hình cũ của next/font/google
const SUBSETS = ["latin", "vietnamese"];

// Tên biến CSS (class) đang được dùng trong code -> font tương ứng
const VARIABLES = {
  "--font-be": ["Be Vietnam Pro", "sans-serif"],
  "--font-card-serif": ["Cormorant Garamond", "serif"],
  "--font-card-script": ["Great Vibes", "cursive"],
  "--font-card-sans": ["Be Vietnam Pro", "sans-serif"],
  "--ev-serif": ["Cormorant Garamond", "serif"],
  "--ev-mono": ["Space Mono", "monospace"],
  "--ev-sans": ["Be Vietnam Pro", "sans-serif"],
  "--ev-display": ["Oswald", "sans-serif"],
  "--ev-script": ["Great Vibes", "cursive"],
  "--font-tpl-ui": ["Be Vietnam Pro", "sans-serif"],
  "--font-tpl-display": ["Cormorant Garamond", "serif"],
};

const outDir = join(root, "public", "fonts");
rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

const faces = [];
let copied = 0;
for (const f of FONTS) {
  const pkgDir = join(root, "node_modules", "@fontsource", f.pkg);
  if (!existsSync(pkgDir)) throw new Error(`Thiếu @fontsource/${f.pkg}. Chạy: npm install`);
  const files = f.weights.flatMap((w) => f.styles.map((st) => `${w}${st === "italic" ? "-italic" : ""}.css`));
  for (const cssFile of files) {
  const cssPath = join(pkgDir, cssFile);
  if (!existsSync(cssPath)) throw new Error(`Thiếu ${f.pkg}/${cssFile}`);
  const css = readFileSync(cssPath, "utf8");
  // Mỗi khối: /* <tên-file> */ @font-face { ... }
  const re = /\/\*\s*([^*]+?)\s*\*\/\s*@font-face\s*\{([\s\S]*?)\}/g;
  let m;
  while ((m = re.exec(css))) {
    const id = m[1];
    const rest = id.slice(f.pkg.length + 1); // ví dụ: vietnamese-400-normal
    const parts = rest.match(/^(latin|vietnamese)-(\d+)-(normal|italic)$/);
    if (!parts || !SUBSETS.includes(parts[1])) continue;
    // Chỉ giữ định dạng woff2, đổi đường dẫn về /fonts/
    const body = m[2].replace(
      /src:\s*url\(\.\/files\/([^)]+)\.woff2\)[^;]*;/,
      (_, file) => `src: url(/fonts/${file}.woff2) format('woff2');`,
    );
    const file = `${id}.woff2`;
    copyFileSync(join(pkgDir, "files", file), join(outDir, file));
    copied++;
    faces.push(`/* ${id} */\n@font-face {${body}}`);
  }
  }
}

const vars = Object.entries(VARIABLES).map(([v, [name, fb]]) =>
  `.${v} {\n  ${v}: '${name}', ${fb};\n}`,
);

writeFileSync(
  join(root, "src", "styles", "local-fonts.css"),
  `/* GENERATED by scripts/build-local-fonts.mjs - không sửa tay */\n\n${faces.join("\n\n")}\n\n/* Biến font dùng bởi các component */\n${vars.join("\n\n")}\n`,
);
console.log(`Đã tạo ${copied} file woff2 và src/styles/local-fonts.css`);
